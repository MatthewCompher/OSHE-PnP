"""Dry-run G-code: the job's placements as a G-code file (optional, next to the job file).

The machine runs jobs from the .job.json file (pnpvision run-job: vision, feeders, retries). This
file is the same placement list written as G-code: for each part to place, in job order, one move
in BOARD coordinates (mm, the job file's frame) followed by a short pause, so a down camera could
visit each placement without picking anything.

Board coordinates, not machine coordinates: where the board sits on the plate is only known after
the machine aligns it. Like a CNC work offset, the PNP_BOARD_MOVE macro is meant to turn board X/Y
into a machine move with the alignment the machine saved. PNP_DRYRUN_START / PNP_BOARD_MOVE /
PNP_DRYRUN_END are not in the machine's Klipper config yet: a printer without them stops at the
first line (unknown command) and nothing moves.
"""

from __future__ import annotations

import os

from .job import FORMAT

PAUSE_MS = 400


def dryrun_path(job_path: str) -> str:
    """'.../Test PCB-top.job.json' -> '.../Test PCB-top_dryrun.gcode'."""
    base = job_path[:-len(".job.json")] if job_path.endswith(".job.json") else os.path.splitext(job_path)[0]
    return base + "_dryrun.gcode"


def _num(v: float) -> str:
    return f"{float(v):.4f}"


def dryrun_gcode(job: dict) -> str:
    """The G-code text for a job dict (as built by job.build_job)."""
    board = job.get("board", {})
    todo = [p for p in job.get("placements", []) if not p.get("skip")]
    name = f"{board.get('name', '?')}-{board.get('side', '?')}"
    src = ", ".join((job.get("source") or {}).get("inputs", [])) or "?"
    lines = [
        f"; OSHE-PnP dry-run G-code, {FORMAT} job '{name}'",
        f"; generated by {(job.get('source') or {}).get('generator', 'pnpslice')} from {src}"
        f" on {(job.get('source') or {}).get('date', '?')}",
        f"; {len(todo)} placements, in job order. X/Y are BOARD coordinates in mm (the job file's frame);",
        "; PNP_BOARD_MOVE turns them into a machine move using the board alignment saved on the machine,",
        "; so the file does not depend on where the board sits on the plate. Nothing is picked or placed.",
        "; Production jobs run from the .job.json file (vision, feeders, retries).",
        ";",
        f"PNP_DRYRUN_START JOB=\"{name}\" PARTS={len(todo)}",
    ]
    for n, p in enumerate(todo, 1):
        lines.append(f"; {n}/{len(todo)} {p.get('ref', '?')} {p.get('package', '')} rot {p.get('rot', 0)}")
        lines.append(f"PNP_BOARD_MOVE X={_num(p['x'])} Y={_num(p['y'])} N={n} REF={p.get('ref', '?')}")
        lines.append(f"G4 P{PAUSE_MS}")
    lines.append("PNP_DRYRUN_END")
    return "\n".join(lines) + "\n"


def write_dryrun_gcode(job_path: str, job: dict) -> str:
    """Write the dry-run G-code next to the job file; returns its path."""
    path = dryrun_path(job_path)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(dryrun_gcode(job))
    os.replace(tmp, path)
    return path
